export function findRegion(code: string): { province: Province; district: District } | null {
  for (const province of PROVINCES) {
    const district = province.districts.find((x) => x.code === code);
    if (district) return { province, district };
  }
  return null;
}

export function regionLabel(code: string): string {
  const r = findRegion(code);
  return r ? `${r.province.name} ${r.district.name}` : code;
}

